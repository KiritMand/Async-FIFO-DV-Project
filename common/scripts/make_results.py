# Tool versions over every record: one value per tool, or every value seen if they differ.
def tools_line(sections: list[Section]) -> str:
    seen: dict[str, set[str]] = collections.defaultdict(set)
    for s in sections:
        for p in s.provs:
            for k, v in ((p or {}).get("tools") or {}).items():
                seen[k].add(v)
    if not seen:
        return "Tools: not recorded."
    parts = [f"{k} {' / '.join(sorted(v))}" + (" (**differs between results**)" if len(v) > 1 else "")
             for k, v in seen.items()]
    return "Tools: " + "; ".join(parts) + "."


# The summary block shared with the README: criteria table, commit and tools.
def summary_block(sections: list[Section], repo: Path, when: str) -> list[str]:
    commits = sorted({provenance.short(p) for s in sections for p in s.provs if p})
    not_current = [s.key for s in sections if s.found and s.prov_status(repo)[0] != "CURRENT"]
    lines = [BEGIN, "", "| ID | Criterion | Result | Status |", "|---|---|---|---|"]
    lines += [f"| {s.key} | {s.criterion} | {s.result or '—'} | {s.status(repo)} |" for s in sections]
    lines += ["", f"Generated {when} from the saved results of commit(s) {', '.join(commits) or 'unknown'}; "
              + ("every result's inputs match this tree." if not not_current else
                 f"**not current:** {', '.join(not_current)} (see the provenance table in the results page)."),
              "", tools_line(sections), "", END]
    return lines


# The whole results page.
def page(sections: list[Section], repo: Path, ip: str, when: str) -> str:
    L = [f"# {ip} — results", "",
         "Reviewer-facing summary of the verification evidence. Generated by `make results` "
         "(`common/scripts/make_results.py`) from the results the flows saved under `out/`; no number on this "
         "page is typed by hand. Each section names the saved result it comes from and the command that "
         "reproduces it. Paths are relative to `ip/" + ip + "/` unless they start with `common/`.", "",
         "## Summary", "", *summary_block(sections, repo, when), "",
         "## Provenance", "",
         "A result is CURRENT when every flow input (RTL, testbench, properties, flows, scripts, the vplan) has "
         "the content it had when the flow ran (`common/scripts/provenance.py`).", "",
         "| Section | Saved result (under `out/" + ip + "/`) | Generated | Commit | Inputs | Reproduce |",
         "|---|---|---|---|---|---|"]
    for s in sections:
        if not s.found:
            L.append(f"| {s.key} | — | — | — | **MISSING** | — |")
            continue
        st, det = s.prov_status(repo)
        commits = ", ".join(sorted({provenance.short(p) for p in s.provs if p})) or "unknown"
        L.append(f"| {s.key} | {', '.join(f'`{x}`' for x in s.sources)} | {s.generated} | {commits} | "
                 f"{st}" + ("" if st == "CURRENT" else f": {det}") + f" | `{s.repro}` |")
    titles = {"SO-2": "Simulation regression (SO-2)", "SO-1": "Coverage (SO-1)", "SVA-neg": "Negative SVA tests",
              "SO-3": "Formal (SO-3)", "CDC": "Structural CDC", "Q-1": "Planted bugs (Q-1)",
              "Q-2": "Mutation coverage (Q-2)"}
    for s in sections:
        L += ["", f"## {titles.get(s.key, s.key)}", ""]
        if not s.found:
            L.append("**No saved result.** Run `" + (s.repro or "the flow") + "`.")
            continue
        L += s.body
        if s.problems:
            L += ["", "**Problems:**", ""] + [f"- {p}" for p in s.problems]
    return "\n".join(L) + "\n"


# Replace the README's block between the markers (the markers must already be there).
def splice(readme: str, block: list[str]) -> str:
    i, j = readme.find(BEGIN), readme.find(END)
    if i < 0 or j < i:
        raise ValueError("README has no results block markers")
    return readme[:i] + "\n".join(block) + readme[j + len(END):]


# The block between the markers of a file, or None.
def block_of(text: str) -> str | None:
    i, j = text.find(BEGIN), text.find(END)
    return text[i:j + len(END)] if 0 <= i < j else None


# Build every section from the saved results under `out`.
def build(ip_root: Path, out: Path, sim_size: str, mcy_sets: list[str]) -> list[Section]:
    vp = vplan_check.Vplan(ip_root / "docs/vplan.md")
    mdl = vplan_check.check_structure(vp)
    reg = sec_regress(out, mdl)
    return [sec_coverage(out, vp, mdl, reg), reg, sec_formal(out, vp, mdl), sec_sva_neg(out, sim_size),
            sec_cdc(out), sec_bugs(out, ip_root), sec_mcy(out, mcy_sets)]


# Parse arguments; --check compares blocks, otherwise build, write, and (with --strict) judge.
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ip-root", type=Path, required=True, help="the block directory (ip/<name>)")
    ap.add_argument("--out", type=Path, help="the block's output directory (make's OUT)")
    ap.add_argument("--readme", type=Path, help="README whose results block is kept equal to the page's")
    ap.add_argument("--page", type=Path, help="page to write (default <ip-root>/docs/results.md)")
    ap.add_argument("--sim-size", default="a4_d8", help="size directory of the negative SVA tests")
    ap.add_argument("--mcy-sets", nargs="*", default=[], help="MCY project names under out/mcy/")
    ap.add_argument("--strict", action="store_true", help="fail unless every section exists, is met and CURRENT")
    ap.add_argument("--check", action="store_true", help="only compare the README block with the page's")
    ap.add_argument("--repro", default="make results", help="reproduction command to print")
    a = ap.parse_args(argv)
    ip_root = a.ip_root.resolve()
    pg = a.page or ip_root / "docs/results.md"
    if a.check:
        if not a.readme:
            print("make_results: --check needs --readme", file=sys.stderr)
            return 2
        want, have = block_of(pg.read_text()) if pg.is_file() else None, block_of(a.readme.read_text())
        ok = want is not None and want == have
        print(f"make_results --check {'PASS' if ok else 'FAIL'}: README block "
              f"{'matches' if ok else 'differs from'} {pg.name}" + ("" if want else " (page has no block)")
              + f"   repro: {a.repro}")
        return 0 if ok else 1
    if not a.out:
        print("make_results: --out is required", file=sys.stderr)
        return 2
    repo = provenance.repo_top(ip_root)
    when = datetime.datetime.now().isoformat(timespec="minutes")
    try:
        sections = build(ip_root, a.out.resolve(), a.sim_size, a.mcy_sets)
    except (ValueError, OSError, KeyError) as e:
        print(f"make_results: {e}", file=sys.stderr)
        return 2
    pg.write_text(page(sections, repo, ip_root.name, when))
    if a.readme:
        a.readme.write_text(splice(a.readme.read_text(), summary_block(sections, repo, when)))
    bad = []
    for s in sections:
        st = s.prov_status(repo)
        print(f"  {s.key:8} {s.status(repo):28} {st[0]:8} {s.result[:90]}")
        if not s.found or not s.ok or st[0] != "CURRENT":
            bad.append(s.key)
    verdict = "PASS" if not (a.strict and bad) else "FAIL"
    print(f"make_results {verdict}: wrote {pg}" + (f" and the README block" if a.readme else "")
          + (f"; not met or not current: {', '.join(bad)}" if bad else "") + f"   repro: {a.repro}")
    return 0 if verdict == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
