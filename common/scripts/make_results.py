import vplan_check  # noqa: E402

BEGIN, END = "<!-- results:begin (generated by make results; do not edit) -->", "<!-- results:end -->"
RANK = {"CURRENT": 0, "UNKNOWN": 1, "STALE": 2}


# One section of the page: its summary-table row, its detail text, and what it rests on.
@dataclass
class Section:
    key: str                         # summary ID (SO-1, Q-2, ...)
    criterion: str                   # what is claimed, in the summary table
    kind: str = "criterion"          # "criterion" (met / NOT MET) or "report" (reported)
    result: str = ""                 # summary-table result text
    ok: bool = False                 # criterion met (or report complete)
    found: bool = False              # the saved result exists
    problems: list[str] = field(default_factory=list)
    provs: list[dict | None] = field(default_factory=list)
    sources: list[str] = field(default_factory=list)   # artifact paths, relative to out/
    generated: str = ""
    repro: str = ""
    body: list[str] = field(default_factory=list)       # Markdown lines of the detail section

    # Worst provenance status over every record, with its detail.
    def prov_status(self, repo: Path) -> tuple[str, str]:
        if not self.provs:
            return "UNKNOWN", "no provenance recorded"
        checks = [provenance.check(p, repo) for p in self.provs]
        return max(checks, key=lambda c: RANK[c[0]])

    # Summary-table status: met / NOT MET / reported / MISSING, flagged when not CURRENT.
    def status(self, repo: Path) -> str:
        if not self.found:
            return "**MISSING**"
        s = ("met" if self.ok else "**NOT MET**") if self.kind == "criterion" else \
            ("reported" if self.ok else "**PROBLEMS**")
        p = self.prov_status(repo)[0]
        return s if p == "CURRENT" else f"{s} (**{p}**)"


# Thousands separators for counts.
def n(x: int) -> str:
    return f"{x:,}"


# Read a JSON file, or None if it does not exist.
def load(path: Path) -> dict | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


# Seconds as a short duration.
def dur(s: float) -> str:
    return f"{s:.1f} s" if s < 120 else f"{s / 60:.0f} min"


