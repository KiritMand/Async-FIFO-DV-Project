# SO-2: the sign-off regression (every run passes, N seeds per test, assertions on, reruns identical).
def sec_regress(out: Path, mdl) -> Section:
    s = Section("SO-2", f"Zero failures over N = {mdl.n_seeds} seeds per test, scoreboard and every assertion on")
    d = load(out / "regress/results.json")
    if not d:
        return s
    s.found, s.sources = True, ["regress/results.json", "regress/recheck/recheck.json"]
    meta, runs = d["meta"], d["runs"]
    s.provs, s.generated, s.repro = [meta.get("provenance")], meta["generated"], meta.get("repro", "")
    n_pass = sum(r["status"] == "PASS" for r in runs)
    per_test = collections.Counter(r["test"] for r in runs)
    short = sorted(t for t, c in per_test.items() if c < mdl.n_seeds)
    rc = load(out / "regress/recheck/recheck.json")
    same = sum(r["identical"] for r in rc["runs"]) if rc else 0
    if n_pass != len(runs):
        s.problems.append(f"{len(runs) - n_pass} run(s) did not pass")
    if short:
        s.problems.append(f"fewer than N = {mdl.n_seeds} seeds: {', '.join(short)}")
    if "SVA=0" in s.repro:
        s.problems.append("assertions were off (SVA=0)")
    if not rc or not rc["runs"]:
        s.problems.append("no recheck (run with RECHECK=3)")
    elif same != len(rc["runs"]):
        s.problems.append(f"{len(rc['runs']) - same} recheck log(s) differ")
    s.ok = not s.problems
    s.result = (f"**{n(n_pass)}/{n(len(runs))}** runs pass ({len(per_test)} tests, {len(set(r['id'] for r in runs))} "
                f"entries); {same}/{len(rc['runs']) if rc else 0} random reruns byte-identical")
    # Detail: one row per tests.toml entry.
    rows = collections.OrderedDict()
    for r in runs:
        e = rows.setdefault(r["id"], {"test": r["test"], "plusargs": r.get("plusargs") or "-", "n": 0, "pass": 0})
        e["n"] += 1
        e["pass"] += r["status"] == "PASS"
    s.body = [f"Simulator {meta['sim']}, {meta['jobs']} parallel jobs, {dur(meta['wall_s'])} wall clock for the "
              "build and every run. Every run has the scoreboard, the test checks, the white-box and end-to-end "
              "assertions, the concurrent twins and the `asm_` testbench checks on; a run passes only with a "
              "clean log (common/sim/verilator.patterns).", "",
              "| Entry | Test | Plusargs | Seeds | Pass | Fail |", "|---|---|---|---|---|---|"]
    s.body += [f"| `{i}` | `{e['test']}` | `{e['plusargs']}` | {e['n']} | {e['pass']} | {e['n'] - e['pass']} |"
               for i, e in rows.items()]
    if rc:
        s.body += ["", "Random reruns (log compared byte for byte with the original run):", ""]
        s.body += [f"- {'identical' if r['identical'] else '**DIFFERENT**'}: `{r['repro']}`" for r in rc["runs"]]
    return s


# SO-1: merged functional coverage of the same regression (vplan items and simulation covers) and
# the RTL code coverage.
def sec_coverage(out: Path, vp, mdl, regress: Section) -> Section:
    s = Section("SO-1", "100% of the vplan coverage model, merged over every seed and clock ratio")
    f, c = load(out / "cov/functional.json"), load(out / "cov/code.json")
    if not f:
        return s
    s.found, s.sources = True, ["cov/functional.json", "cov/code.json"]
    s.provs, s.generated, s.repro = regress.provs, f["generated"], regress.repro   # merged by the same run
    k = vplan_check.so1_counts(vp, mdl, f)
    runs = load(out / "regress/results.json")
    n_pass = sum(r["status"] == "PASS" for r in runs["runs"]) if runs else -1
    if k["hit"] != k["bins"] or k["missing"]:
        s.problems.append(f"{k['bins'] - k['hit']} hole(s), missing items {k['missing']}")
    if k["stated"] is not None and k["stated"] != k["bins"]:
        s.problems.append(f"the vplan states {k['stated']} bins, the database has {k['bins']}")
    if k["covers_hit"] != k["covers"]:
        s.problems.append(f"{k['covers'] - k['covers_hit']} simulation cover(s) never hit")
    if f["merged_runs"] != n_pass:
        s.problems.append(f"merged {f['merged_runs']} runs, but {n_pass} passed")
    s.ok = not s.problems
    code = []
    for path, m in (c or {}).get("files", {}).items():
        code.append(f"`{Path(path).name}` " + ", ".join(f"{kind} {v['hit']}/{v['points']}" for kind, v in m.items()))
    s.result = (f"**{k['hit']}/{k['bins']}** planned bins, **{k['covers_hit']}/{k['covers']}** simulation covers "
                f"({n(f['merged_runs'])} runs merged)")
    s.body = [f"Merged over {n(f['merged_runs'])} passing runs. Every planned bin was hit at least "
              f"{n(k['thinnest'])} times, every simulation cover at least {n(k['covers_thinnest'])} times. "
              "Per-item detail: `docs/vplan_status.md`.", "",
              "| Covergroup | Items | Bins | Hit |", "|---|---|---|---|"]
    for g, gd in f["groups"].items():
        items = gd["items"]
        nb = sum(len(i["bins"]) for i in items.values())
        nh = sum(sum(v > 0 for v in i["bins"].values()) for i in items.values())
        s.body.append(f"| `{g}` | {len(items)} | {nb} | {nh} |")
    s.body += ["", "The covergroup totals include helper coverpoints used only to build crosses; the planned-bin "
               "count above leaves them out, as the vplan does.", "",
               "RTL code coverage (Verilator, RTL only): " + ("; ".join(code) or "not recorded") + "."]
    return s


# Negative SVA tests: every simulation assertion fires when its property is broken on purpose.
def sec_sva_neg(out: Path, size: str) -> Section:
    s = Section("SVA-neg", "Every simulation assertion fires when its property is broken")
    d = load(out / f"sva_neg/{size}/results.json")
    if not d:
        return s
    s.found, s.sources, s.provs = True, [f"sva_neg/{size}/results.json"], [d.get("provenance")]
    s.generated = (d.get("provenance") or {}).get("time", "")
    s.repro = "make sva-neg"
    cases, twins = d["cases"], d["twins"]
    fired = sum(c["status"] == "PASS" for c in cases)
    tw = sum(t["fires"] for t in twins)
    s.problems = list(d["problems"]) + ([] if d["clean"]["ok"] else ["the clean run was not quiet"])
    s.ok = not s.problems and fired == len(cases) and tw == len(twins)
    by = collections.Counter(c["label"].split("_")[0] for c in cases)
    s.result = (f"**{fired}/{len(cases)}** assertions fire when broken ({', '.join(f'{v} `{k}_`' for k, v in sorted(by.items()))}); "
                f"**{tw}/{len(twins)}** concurrent twins fire with them; clean run quiet")
    s.body = [f"Each case breaks one property by forcing a signal or driving illegal stimulus and expects that "
              f"assertion to fire. No case: {', '.join(f'`{k}` ({v})' for k, v in d['nocases'].items()) or 'none'}. "
              "Per-case detail: `docs/sva_negative_tests.md`."]
    return s


# Formal task names, what they show, and whether a task belongs to the SO-3 sign-off set.
FORMAL_TASKS = {
    "prove": ("Every assertion (spec + `inv_` invariants) holds unbounded: k-induction", True),
    "cover": ("Every formal cover is reached", True),
    "pdr": ("Every assertion, ABC PDR (finds its own invariants)", True),
    "bmc": ("Bounded check of every assertion", True),
    "audit_a01": ("Drop A01 (resets asserted at power-up): must fail", False),
    "audit_a05": ("Drop A05 (no reset after power-up): must fail", False),
    "prove_noinv": ("k-induction without the hand-written invariants (recorded)", False),
    "pdr_noinv": ("PDR without the hand-written invariants (recorded)", False),
}


# One formal cell: verdict, plus covers reached or failing assertions, and the time.
def formal_cell(r: dict | None) -> str:
    if r is None:
        return "not run"
    v = r["verdict"]
    extra = ""
    if r["task"] == "cover":
        tot = len(r["reached"]) + len(r["unreached"])
        v, extra = f"{len(r['reached'])}/{tot}", " covers"
    elif r["failed"] and v != "PASS":
        extra = f", {len(r['failed'])} assertion(s)"
    t = f"{dur(r['seconds'])}" if v != "TIMEOUT" else f"at {dur(r['seconds'])}"
    mark = "" if r["ok"] else " **(not as expected)**"
    return (f"**{v}**" if r["task"] in ("prove", "cover", "pdr") else v) + f"{extra}, {t}{mark}"


# SO-3: the formal sign-off (prove and cover at ASIZE 2 and 3, assumption audit, cross-checks).
def sec_formal(out: Path, vp, mdl) -> Section:
    s = Section("SO-3", "Formal: every assertion proven unbounded and every cover reached, ASIZE 2 and 3")
    d = load(out / "formal/signoff.json")
    if not d:
        return s
    s.found, s.sources = True, ["formal/signoff.json"]
    s.provs, s.generated, s.repro = [d["meta"].get("provenance")], d["meta"]["generated"], d["meta"]["repro"]
    excluded = {t for r in vp.tables["exclusions"] for t in vplan_check.tokens(r["Item"])}
    _, _, nprob = vplan_check.formal_status(mdl, d, excluded)
    s.ok = nprob == 0
    if not s.ok:
        s.problems.append(f"{nprob} SO-3 problem(s) (see docs/vplan_status.md)")
    runs = {(r["task"], r["asize"]): r for r in d["runs"]}
    sizes = sorted({r["asize"] for r in d["runs"]})
    prove = [a for a in sizes if runs.get(("prove", a), {}).get("verdict") == "PASS"]
    cov = [f"{len(runs[('cover', a)]['reached'])}/{len(runs[('cover', a)]['reached']) + len(runs[('cover', a)]['unreached'])}"
           f" at {a}" for a in sizes if ("cover", a) in runs]
    pdr = [f"{a}: {runs[('pdr', a)]['verdict']}" for a in sizes if ("pdr", a) in runs]
    s.result = (f"k-induction **PASS** at ASIZE {', '.join(map(str, prove)) or 'none'}; covers "
                f"**{', '.join(cov)}**; PDR {', '.join(pdr)}")
    head = "| Task | What it shows | " + " | ".join(f"ASIZE={a}" for a in sizes) + " |"
    sep = "|---|---|" + "---|" * len(sizes)
    s.body = [f"Open-source SymbiYosys, `multiclock on`, DSIZE = {d['meta']['dsize']}, free clocks (A04), "
              "assumptions A01 and A05 (vplan §5; A02 is not assumed, DEC-012). Method, invariants and the "
              "ZipCPU comparison: `docs/formal_notes.md`.", "", "**Sign-off set**", "", head, sep]
    for t, (what, so3) in FORMAL_TASKS.items():
        if so3 and any((t, a) in runs for a in sizes):
            s.body.append(f"| `{t}` | {what} | " + " | ".join(formal_cell(runs.get((t, a))) for a in sizes) + " |")
    s.body += ["", "**Assumption audit and cross-checks**", "", head, sep]
    for t, (what, so3) in FORMAL_TASKS.items():
        if not so3 and any((t, a) in runs for a in sizes):
            s.body.append(f"| `{t}` | {what} | " + " | ".join(formal_cell(runs.get((t, a))) for a in sizes) + " |")
    other = sorted({t for t, _ in runs} - set(FORMAL_TASKS))
    if other:
        s.body += ["", f"Other tasks in the run: {', '.join(f'`{t}`' for t in other)}."]
    s.body += ["", "Figures (cover traces, `make formal-figures`): `docs/figures/formal_fill_full_drain_a2.svg`, "
               "`docs/figures/formal_pointer_wrap_a2.svg`."]
    return s


# Structural CDC: no unwaived violation of rules R1–R3 on the synthesized netlist.
def sec_cdc(out: Path) -> Section:
    s = Section("CDC", "Structural CDC rules R1–R3 hold on the synthesized netlist")
    d = load(out / "cdc/report.json")
    if not d:
        return s
    s.found, s.sources, s.provs = True, ["cdc/report.json"], [d.get("provenance")]
    s.generated, s.repro = (d.get("provenance") or {}).get("time", ""), "make cdc"
    open_v = [v for v in d["violations"] if not v["waived_by"]]
    waived = [v for v in d["violations"] if v["waived_by"]]
    syncs = [x for x in d["notes"] if x["rule"] == "R4"]
    s.ok = not open_v
    s.problems = [f"{v['rule']}: {v['msg']}" for v in open_v]
    s.result = f"**{len(open_v)}** violations, {len(waived)} waived, {len(syncs)} multi-bit gray synchronizers"
    s.body = ["Rules (`common/scripts/cdc_check.py`, domains and waivers in `constraints/cdc.toml`): R1 no logic "
              "on a crossing, R2 the first synchronizer stage feeds only the second, R3 each stage is reset in "
              "its destination domain. R4 notes multi-bit synchronizers, which are safe only for gray-coded "
              "sources (checked by the F09 properties, not structurally).", ""]
    s.body += [f"- Waived {v['rule']}: {v['msg']} (reason: {v['waived_by']}; vplan §8)" for v in waived]
    s.body += [f"- **Violation** {v['rule']}: {v['msg']}" for v in open_v]
    s.body += [f"- Note {x['rule']}: {x['msg']}" for x in syncs]
    return s


# Q-1: the planted-bug detection matrix (bug_matrix.py's own cell logic).
CAUGHT = {"static": ("yes",), "cdc": ("yes",), "sim_sb": ("yes", "stim"), "sim_sva": ("yes", "stim"),
          "formal": ("e2e", "white-box", "other"), "prove": ("fail",)}
METHOD = {"sim_sb": "simulation, UVM checks only", "sim_sva": "simulation with every assertion",
          "formal": "formal spec bmc", "prove": "k-induction fails", "cdc": "structural CDC", "static": "lint/synth"}


def sec_bugs(out: Path, ip_root: Path) -> Section:
    s = Section("Q-1", "Detection matrix for planted bugs: simulation vs. SVA vs. formal", kind="report")
    if not (out / "bugs/base").is_dir():
        return s
    d = bug_matrix.summarize(ip_root, (out / "bugs").resolve())
    bugs = [b for b in d["bugs"] if b["id"] != bug_matrix.BASE_ID]
    s.found, s.sources, s.provs = True, ["bugs/<id>/<part>.json"], d["provenance"] or [None]
    s.generated = max(((p or {}).get("time", "") for p in s.provs), default="")
    s.repro, s.problems = "make bugs", d["problems"]
    s.ok = not s.problems
    count = {m: sum(b["cells"].get(m) in CAUGHT[m] for b in bugs) for m in CAUGHT}
    any_m = sum(any(b["cells"].get(m) in CAUGHT[m] for m in CAUGHT if m != "prove") for b in bugs)
    s.result = (f"{len(bugs)} bugs; caught by {METHOD['sim_sb']} **{count['sim_sb']}**, "
                f"{METHOD['sim_sva']} **{count['sim_sva']}**, {METHOD['formal']} **{count['formal']}**, "
                f"{METHOD['cdc']} **{count['cdc']}**; by at least one method **{any_m}/{len(bugs)}**")
    sims = [v for b in d["bugs"] for v in b["sim"].values() if v]
    total = sims[0][1] if sims else 0
    s.body = [f"Simulation: {len(d['tests'])} tests × {d['seeds']} seeds = {total} runs per bug and method; "
              f"formal at ASIZE = {d['formal_asize']}. Cells say whether the method caught the bug (simulation: "
              "failing runs out of all runs). Predictions, explanations of every surprise, and per-bug detail: "
              "`docs/bug_matrix.md`.", "",
              "| Bug | Lint/synth | CDC | Sim: UVM checks | Sim: all assertions | Formal bmc | Prove | Covers lost |",
              "|---|---|---|---|---|---|---|---|"]
    yn = lambda v, m: "caught" if v in CAUGHT[m] else ("—" if v in ("no", "pass") else str(v))  # noqa: E731
    for b in d["bugs"]:
        c, sim = b["cells"], b["sim"]
        simc = lambda p: f"{sim[p][0]}/{sim[p][1]}" if sim[p] else str(c.get(p))  # noqa: E731
        lost = c.get("covers_lost")
        s.body.append(f"| {b['id']} {b['title']} | {yn(c.get('static'), 'static')} | {yn(c.get('cdc'), 'cdc')} | "
                      f"{simc('sim_sb')} | {simc('sim_sva')} | {'—' if c.get('formal') == 'no' else c.get('formal')} | "
                      f"{'not proven' if c.get('prove') == 'fail' else str(c.get('prove')).upper()} | "
                      f"{len(lost) if isinstance(lost, list) else lost} |")
    return s


# Q-2: MCY mutation scores per set, plus the scoreboard-only probe.
def sec_mcy(out: Path, sets: list[str]) -> Section:
    s = Section("Q-2", "MCY mutation score per method, every surviving mutant explained", kind="report")
    rows, results, probe_lines = [], [], []
    for name in sets:
        d, meta = load(out / f"mcy/{name}/summary.json"), load(out / f"mcy/{name}/meta.json") or {}
        if not d:
            s.problems.append(f"no MCY result {name}")
            continue
        s.found = True
        s.sources.append(f"mcy/{name}/summary.json")
        s.provs += [d.get("provenance")] + d.get("provenance_resumes", [])
        s.generated = max(s.generated, d.get("finished", ""))
        s.problems += [f"{name}: {p}" for p in d["problems"]]
        c, sc = d["counts"], d["score"]
        rows.append(f"| seed {d['seed']} | {d['size']} | {d['denominator']} | **{sc['simulation']:.1f}%** | "
                    f"**{sc['formal']:.1f}%** | **{sc['combined']:.1f}%** | {c['UNCOVERED']} | {c['EQGAP']} | "
                    f"{c['NOCHANGE']} | {dur(meta.get('wall_s', 0))} |")
        results.append(f"seed {d['seed']}: {d['denominator']} non-equivalent, sim {sc['simulation']:.0f}% / "
                       f"formal {sc['formal']:.0f}%, {c['UNCOVERED']} survivors")
        s.repro = s.repro or d["repro"]
        for probe in sorted((out / f"mcy/{name}/probe").glob("*/probe.json")):
            p = load(probe)
            s.sources.append(f"mcy/{name}/probe/{probe.parent.name}/probe.json")
            s.provs.append(p.get("provenance"))
            k = p["counts"]
            det = k["both"] + k["probe_only"]
            results.append(f"probe `{p['extra_vars']}` on seed {d['seed']}: {det}/{d['denominator']} detected")
            probe_lines.append(
                f"- Probe `{p['name']}` (`{p['extra_vars']}`) on seed {d['seed']}: detects {det} of "
                f"{d['denominator']} non-equivalent mutants; caught only with the full checks: {k['project_only']}. "
                f"Repro: `{p['repro']}`")
    if not s.found:
        return s
    s.ok = not s.problems
    s.result = "; ".join(results)
    s.body = [f"MCY on the RTL at ASIZE = 2, DSIZE = 4 (DEC-014): every mutant gets simulation (the UVM testbench "
              "on the mutated netlist, a coverage-preserving run subset), equivalence (two-copy miter, ABC PDR) "
              "and formal (the mutant with the e2e checker's spec properties, ABC PDR). Score = detected / "
              "non-equivalent. Per-mutant detail: `docs/mutation_report.md`.", "",
              "| Set | Mutants | Non-equivalent | Simulation | Formal | Combined | UNCOVERED | EQGAP | NOCHANGE | Wall clock |",
              "|---|---|---|---|---|---|---|---|---|---|", *rows]
    if probe_lines:
        s.body += ["", *probe_lines]
    return s


