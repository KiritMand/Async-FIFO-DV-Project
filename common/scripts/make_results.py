#!/usr/bin/env python3
"""make_results.py — build a block's reviewer-facing results page from its saved results (M10).

Reads only what the flows saved under the block's out/ directory, never a hand-typed number:
  regress/results.json, regress/recheck/recheck.json, cov/{functional,code}.json   (SO-1, SO-2)
  sva_neg/<size>/results.json                                                      (negative SVA tests)
  formal/signoff.json                                                              (SO-3)
  cdc/report.json                                                                  (structural CDC)
  bugs/<id>/<part>.json, through bug_matrix.summarize()                            (Q-1)
  mcy/<set>/{summary,meta}.json and mcy/<set>/probe/<name>/probe.json              (Q-2)
Each saved result carries a provenance record (provenance.py): the commit it ran at, and its
uncommitted inputs. Every section is marked CURRENT when the flow inputs in today's tree are
the ones it ran on, STALE when an input changed since, UNKNOWN when nothing was recorded.

Writes <ip-root>/docs/results.md, and copies the page's summary block (between the markers
below) into the README, so the README cannot drift from the page. --check compares the two
blocks without reading out/ (CI runs it). --strict fails unless every section exists, meets its
criterion and is CURRENT (the release run).

Exit status: 0 ok, 1 --strict or --check failed, 2 usage error. Python >= 3.11, standard library only.
"""

from __future__ import annotations

import argparse
